#!/usr/bin/env node
// Builds sfx/data/credits.json: who made every recording the sound library plays.
//
//   node sfx/tools/build-credits.mjs
//
// Every recording fetched by sfx/tools/freesound.py has a `<file>.ogg.json` credit beside it (title,
// author, url, licence). This gathers them, keeps only the files the catalog actually uses, groups
// them by author, and adds the Kenney packs. shared/credits.js and credits.html read the result.
// Run it after build-catalog.py whenever recordings change; tests/sfx.test.js fails if a file the
// catalog plays has no credit.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SFX = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(SFX, 'data/catalog.json'), 'utf8'));

const KENNEY = {
  rpg: { title: 'RPG Audio', url: 'https://kenney.nl/assets/rpg-audio' },
  impact: { title: 'Impact Sounds', url: 'https://kenney.nl/assets/impact-sounds' },
  interface: { title: 'Interface Sounds', url: 'https://kenney.nl/assets/interface-sounds' },
};

export function buildCredits() {
  const used = new Set();
  for (const s of catalog.sounds) for (const f of s.library?.files || []) used.add(f);
  const packs = new Map(), byKey = new Map(), missing = [];
  for (const f of [...used].sort()) {
    const k = /^kenney\/([^/]+)\//.exec(f);
    if (k) { const p = KENNEY[k[1]]; if (p) packs.set(k[1], { title: `Kenney — ${p.title}`, author: 'Kenney (kenney.nl)', url: p.url, license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' }); continue; }
    const cf = join(SFX, 'assets', f + '.json');
    if (!existsSync(cf)) { missing.push(f); continue; }
    const c = JSON.parse(readFileSync(cf, 'utf8'));
    const key = c.url || `${c.author}:${c.title}`;
    if (!byKey.has(key)) byKey.set(key, { title: c.title, author: c.author, url: c.url, license: c.license, licenseUrl: c.licenseUrl, source: c.source, files: [] });
    byKey.get(key).files.push(f);
  }
  const recordings = [...byKey.values()].sort((a, b) => a.author.localeCompare(b.author, 'en', { sensitivity: 'base' }) || a.title.localeCompare(b.title));
  return { about: 'Generated by sfx/tools/build-credits.mjs — do not edit by hand.', packs: [...packs.values()], recordings, missing };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = buildCredits();
  writeFileSync(join(SFX, 'data/credits.json'), JSON.stringify(out, null, 1) + '\n');
  const authors = new Set(out.recordings.map(r => r.author));
  console.log(`wrote sfx/data/credits.json: ${out.recordings.length} recordings by ${authors.size} authors, ${out.packs.length} packs${out.missing.length ? `, ${out.missing.length} WITHOUT a credit: ${out.missing.join(', ')}` : ''}`);
  if (out.missing.length) process.exitCode = 1;
}
