// Credits — who made the third-party things a game uses (owner 2026-10-29: "add a credits page to list
// the author of all the third party assets that require or ask for accreditation").
//
//   import { createCredits } from '../../shared/credits.js';     // + <link rel="stylesheet" href=".../shared/credits.css">
//   const credits = createCredits({ game: 'kindlewild', title: 'Credits', made: 'Made by Radley Sustaire' });
//   el.append(credits.button({ label: 'Credits' }));   // or credits.open()
//
// Reads two files next to this module: shared/credits.json (fonts, code, art — hand-kept, each row says
// which games use it) and sfx/data/credits.json (every recording the shared sound library plays,
// generated by sfx/tools/build-credits.mjs). `sounds: false` leaves the sound list out for a game that
// does not use the library. The window is a `.modal` with a [data-close] button, like What's new, so
// pad navigation that walks the top `.modal` works in it. credits.html (playground root) shows the lot.

const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const SHARED = new URL('./credits.json', import.meta.url);
const SOUNDS = new URL('../sfx/data/credits.json', import.meta.url);

async function getJson(url) { try { const r = await fetch(url, { cache: 'no-cache' }); if (r.ok) return await r.json(); } catch { /* offline */ } return null; }

/** Pure: the sections to show for one game (or every game when `game` is null). */
export function creditSections(shared, sounds, { game = null, includeSounds = true } = {}) {
  const out = [];
  if (includeSounds && sounds) {
    const items = [...(sounds.recordings || [])];
    if (items.length || sounds.packs?.length) out.push({ id: 'sounds', title: 'Sound effects', note: 'Recordings from freesound.org and Kenney, all public domain (CC0) — credited with thanks even where the licence does not ask for it.', packs: sounds.packs || [], items });
  }
  for (const g of shared?.groups || []) {
    const items = g.items.filter(i => !game || !i.games || i.games.includes('*') || i.games.includes(game));
    if (items.length) out.push({ id: g.id, title: g.title, items });
  }
  return out;
}

export async function loadCredits(opts = {}) {
  const [shared, sounds] = await Promise.all([getJson(SHARED), opts.includeSounds === false ? null : getJson(SOUNDS)]);
  return creditSections(shared, sounds, opts);
}

const lic = i => i.licenseUrl ? `<a href="${esc(i.licenseUrl)}" target="_blank" rel="noopener">${esc(i.license)}</a>` : esc(i.license || '');
const name = i => i.url ? `<a href="${esc(i.url)}" target="_blank" rel="noopener">${esc(i.title)}</a>` : esc(i.title);

/** HTML for the sections (used by the window and by credits.html). */
export function creditsHtml(sections) {
  if (!sections.length) return '<p class="cr-empty">Could not load the credits list.</p>';
  return sections.map(s => {
    let body = '';
    if (s.id === 'sounds') {
      const byAuthor = new Map();
      for (const r of s.items) { if (!byAuthor.has(r.author)) byAuthor.set(r.author, []); byAuthor.get(r.author).push(r); }
      body = (s.packs.length ? `<ul class="cr-list">${s.packs.map(p => `<li><b>${name(p)}</b> by ${esc(p.author)} <span class="cr-lic">${lic(p)}</span></li>`).join('')}</ul>` : '')
        + `<ul class="cr-list cr-authors">${[...byAuthor].map(([a, rs]) => `<li><b>${esc(a)}</b> <span class="cr-lic">${lic(rs[0])}</span><span class="cr-works">${rs.map(name).join(' · ')}</span></li>`).join('')}</ul>`;
    } else {
      body = `<ul class="cr-list">${s.items.map(i => `<li><b>${name(i)}</b> by ${esc(i.author)} <span class="cr-lic">${lic(i)}</span></li>`).join('')}</ul>`;
    }
    return `<section class="cr-section"><h3>${esc(s.title)}</h3>${s.note ? `<p class="cr-note">${esc(s.note)}</p>` : ''}${body}</section>`;
  }).join('');
}

export function createCredits({ game = null, title = 'Credits', made = '', sounds = true } = {}) {
  let root = null;
  function close() { root?.remove(); root = null; }
  async function open() {
    close();
    root = document.createElement('div');
    root.className = 'modal cr-modal';
    root.setAttribute('role', 'dialog'); root.setAttribute('aria-label', title);
    root.innerHTML = `<div class="cr-panel"><header class="cr-head"><h2>${esc(title)}</h2><button type="button" class="cr-x" data-close aria-label="Close">×</button></header><div class="cr-body">${made ? `<p class="cr-made">${esc(made)}</p>` : ''}<p class="cr-empty">Loading…</p></div></div>`;
    root.addEventListener('click', e => { if (e.target === root || e.target.closest('[data-close]')) close(); });
    root.addEventListener('keydown', e => { if (e.key === 'Escape') { e.stopPropagation(); close(); } });
    document.body.append(root);
    root.querySelector('.cr-x')?.focus({ preventScroll: true });
    const me = root;
    const sections = await loadCredits({ game, includeSounds: sounds });
    if (root !== me) return;
    root.querySelector('.cr-body').innerHTML = (made ? `<p class="cr-made">${esc(made)}</p>` : '') + creditsHtml(sections);
  }
  function button({ label = title, className = '' } = {}) {
    const b = document.createElement('button');
    b.type = 'button'; b.className = `cr-open ${className}`.trim(); b.textContent = label;
    b.addEventListener('click', () => open());
    return b;
  }
  return { open, close, button };
}
