// Maintenance only; the browser uses the checked-in module with no build step.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = p => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const far = read('../prototypes/farhold/data/skills.json');
const tv = read('../prototypes/thousandvale/data/rules/classes-tv.json');
const classes = [...read('../prototypes/farhold/data/classes.json').classes, ...tv.classes];
const skills = { ...far.skills, ...tv.skills };
const metadata = {};
for (const c of classes) for (const id of c.skills) {
  const s = skills[id];
  metadata[id] = { name: s.name, classId: c.id, className: c.name,
    categories: ['spell', s.element || 'arcane', s.shape || 'self'] };
}
const code = '// Generated by icons/tools/sync-metadata.mjs from the game data.\nexport const metadata = ' + JSON.stringify(metadata, null, 2) + ';\n';
writeFileSync(new URL('data/metadata.js', root), code);
console.log(`Synced ${Object.keys(metadata).length} spell names and categories for ${classes.length} classes.`);
