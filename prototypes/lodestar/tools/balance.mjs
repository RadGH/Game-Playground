// Balance run (PLAN §1.1, M3): N seeds through the bot (tools/bot.mjs), written up as research/balance-m3.md.
//
//   node tools/balance.mjs [--seeds 20] [--size small] [--minutes 60] [--out research/balance-m3.md]
//
// What it reports per seed and in total: game minutes to 500 copper bars, when each unlock arrived, what was built,
// how busy the carriers were, which jam lamps lit most, and how much road the bot laid.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { runBot } from './bot.mjs';
import { loadData, ROOT } from './lib-data.mjs';

const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const N = +arg('seeds', 20), size = arg('size', 'small'), minutes = +arg('minutes', 90);
const out = arg('out', ROOT + 'research/balance-m3.md');
const data = loadData();

const rows = [];
const t0 = Date.now();
for (let s = 1; s <= N; s++) {
  const t = Date.now();
  const r = runBot({ seed: s * 101 + 7, size, minutes, data, sample: 1200 });
  delete r.sim;
  r.ms = Date.now() - t;
  rows.push(r);
  process.stdout.write(`seed ${r.seed}: ${r.reached ? r.minutes + ' min' : 'NOT REACHED (' + r.bars + ' bars)'} · ${r.ms} ms\n`);
}
const ok = rows.filter((r) => r.reached);
const mins = ok.map((r) => r.minutes).sort((a, b) => a - b);
const med = (a) => a.length ? a[a.length >> 1] : null;
const jamTotals = {};
for (const r of rows) for (const [k, n] of Object.entries(r.jams)) jamTotals[k] = (jamTotals[k] || 0) + n;
const md = [];
md.push('# Lodestar — balance run, M3 (economy core)', '');
md.push(`Generated by \`node tools/balance.mjs --seeds ${N} --size ${size} --minutes ${minutes}\` on ${new Date().toISOString().slice(0, 10)}. Bot v1 (tools/bot.mjs) plays through the console's own commands. Goal: 500 copper bars made.`, '');
md.push('## Summary', '');
md.push(`| | |`, `|---|---|`);
md.push(`| Seeds that reached 500 bars | **${ok.length} / ${N}** |`);
md.push(`| Game minutes to 500 bars (min / median / max) | ${mins[0] ?? '—'} / ${med(mins) ?? '—'} / ${mins[mins.length - 1] ?? '—'} |`);
md.push(`| Carriers busy (mean share of the time) | ${(rows.reduce((a, r) => a + r.busy, 0) / rows.length).toFixed(2)} |`);
md.push(`| Road laid per game (median, metres) | ${med(rows.map((r) => r.roadCells / 2).sort((a, b) => a - b))} |`);
md.push(`| Outcrops worked out by the goal (median) | ${med(rows.map((r) => r.workedOut).sort((a, b) => a - b))} |`);
md.push(`| Wall-clock per game (median) | ${med(rows.map((r) => r.ms).sort((a, b) => a - b))} ms |`, '');
md.push('## Jam lamps that lit (all seeds)', '', '| building:lamp | times |', '|---|---|');
for (const [k, n] of Object.entries(jamTotals).sort((a, b) => b[1] - a[1])) md.push(`| ${k} | ${n} |`);
md.push('', '## Per seed', '', '| seed | minutes | bars | porters | carts | busy | roads (m) | buildings | unlocks |', '|---|---|---|---|---|---|---|---|---|');
for (const r of rows) md.push(`| ${r.seed} | ${r.minutes ?? '—'} | ${r.bars} | ${r.porters} | ${r.carts} | ${r.busy} | ${r.roadCells / 2} | ${Object.entries(r.buildings).map(([k, n]) => `${k} ${n}`).join(', ')} | ${r.unlocked.join(', ')} |`);
md.push('', '## Copper bars over time (first seed, one sample a game minute)', '', '| minute | copper ore dug | bars made |', '|---|---|---|');
for (const c of rows[0].curve) md.push(`| ${c.min} | ${c.ore} | ${c.bars} |`);
md.push('', `Total run: ${((Date.now() - t0) / 1000).toFixed(1)} s.`, '');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md.join('\n'));
console.log(`\n${ok.length}/${N} reached; median ${med(mins)} min → ${out}`);
