// The list of every door in the game (PLAN M3 pass test), generated from the real town, one row a door:
//   node prototypes/oddhaven/tools/list-doors.mjs      writes data/doors.json
// tests/doors.test.js fails if the file is out of date, then walks all nine races through every row.
import { writeFileSync } from 'node:fs';
import { allDoors } from '../tests/door-list.js';
const rows = allDoors();
writeFileSync(new URL('../data/doors.json', import.meta.url), JSON.stringify({ _doc: 'Every door in the game. Generated by tools/list-doors.mjs; do not edit. [building, trade, door id, floor, kind, from, to, x, z in the building]', count: rows.length, doors: rows }) + '\n');
console.log(rows.length, 'doors');
