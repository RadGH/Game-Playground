import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 390, height: 700 }, deviceScaleFactor: 2 });
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://localhost:8401/prototypes/stoneward/?dev', { waitUntil: 'networkidle' });
await page.click('#btn-new'); await page.click('#nw-go');
await page.waitForFunction(() => window.gameEye.state().screen === 'landing', null, { timeout: 60000 });
await page.evaluate(() => window.gameEye.found()); await page.waitForTimeout(1500);
await page.evaluate(() => { window.gameEye.speed(8); window.gameEye.order({ t: 'time', tod: 0.2 }); });
await page.waitForTimeout(90000);
await page.evaluate(() => window.gameEye.speed(1));
const t = (await page.evaluate(() => window.gameEye.state())).town;
await page.evaluate(() => document.querySelectorAll('.celebrate').forEach(e => e.remove()));
await page.evaluate(([x, y]) => window.gameEye.fly(x, y, 4), [t.towns[0].x, t.towns[0].y]); await page.waitForTimeout(1500);
await page.screenshot({ path: 'test-results/stoneward-pt2/20-streets-close.png' });
await page.evaluate(([x, y]) => window.gameEye.fly(x, y, 2), [t.towns[0].x, t.towns[0].y]); await page.waitForTimeout(1500);
await page.screenshot({ path: 'test-results/stoneward-pt2/21-streets-mid.png' });
console.log('pop', t.pop, 'errors', errs);
await browser.close();
