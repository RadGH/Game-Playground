// World Build — what a world is written as: a map.json in Oathwild's own schema (terrain.js reads every field it knows
// and ignores the rest), a towns.json in Oathwild's towns schema, and the ground in tiles. Pure (the bytes are made
// here; tools/build.mjs writes them to disk, the fly view can fetch them back).
//
// THE MAP FILE: bounds, grid, limits, frame, regions, border, hills, ridges, rivers, roads, crossings, places, areas,
// forests, fields, marshes, spawn — the same fields and meanings as prototypes/oathwild/data/map.json — plus OPT-IN
// fields the game does not read today:
//   baked    { format, tile, cell, path, layers, biomes, regions, tiles: [[tx, tz]…] } — the ground is not rebuilt from
//            hills and ridges any more but read from tiles (heights, water, water kind, biome, region, level, forest).
//            Oathwild adopts it by building its terrain with worldbuild/js/terrain-api.js bakedTerrain() when the map
//            has `baked`, and with createTerrain() as today when it does not (README "Adopting it in Oathwild").
//   lakes, sea, setPieces, generator   — information for tools and the fly view.
//
// A TILE FILE (tiles/<tx>_<tz>.bin): 'WBT1', u32 header length, a JSON header { tx, tz, x0, z0, n, layers: [{ name,
// type, n, offset, bytes }] }, then the layers as raw little-endian arrays: height Float32 n×n (2 m vertices, the
// tile's edges shared with its neighbours), water Float32 n×n (NaN = dry; left out when the tile is dry), kind Uint8
// n×n, biome Uint8 (4 m cells), region / level / forest Uint8 (8 m cells).

import { BIOMES } from './themes.js';
import { TILE } from './detail.js';

export const TILE_VERTS = TILE / 2 + 1;   // 129 vertices along a 256 m tile at 2 m

export function toMapJson(W) {
  const pin = W.pin, b = W.brief;
  const regions = {};
  for (const r of W.regionList) {
    if (r.pinned) { regions[r.id] = { ...pin.lists.regions[r.id] }; continue; }
    regions[r.id] = { name: r.name, levels: r.levels, base: 0, amp: 0, ground: r.ground, forest: r.forest, theme: r.theme };
  }
  const rivers = [];
  if (pin) for (const r of pin.lists.rivers) { const { pinned, ...rest } = r; rivers.push(rest); }
  for (const r of W.rivers) rivers.push({ id: r.id, name: r.name, width: r.width, depth: r.depth, drop: r.drop, points: r.points, kind: r.kind, ...(r.joins ? { joins: r.joins } : {}), ...(typeof r.to === 'string' ? { to: r.to } : {}), generated: true });
  const roads = W.roads.map(r => {
    if (r.pinned) { const src = pin.lists.roads.find(x => x.id === r.id); const { pinned, ...rest } = src; return rest; }
    return { id: r.id, name: r.name, class: r.class, width: r.width, points: r.points, ...(r.town ? { town: r.town } : {}), ...(r.gate ? { gate: r.gate, joins: r.joins } : {}), ...(r.shoulder ? { shoulder: r.shoulder } : {}), generated: true };
  });
  const places = {};
  for (const [id, p] of Object.entries(W.places)) {
    if (p.pinned) { const { pinned, y, id: _, ...rest } = p; places[id] = rest; continue; }
    places[id] = { name: p.name, kind: p.kind, type: p.type, region: p.region, at: p.at, radius: p.radius, flat: p.flat, ...(p.relief ? { relief: p.relief } : {}), levels: p.levels, ...(p.size ? { size: p.size } : {}), generated: true };
  }
  const strip = list => list.map(({ pinned, ...rest }) => rest);
  const tiles = tileList(W);
  return {
    _doc: `Generated by World Build (worldbuild/) from brief "${b.id}" with seed ${W.seed}. Same schema as prototypes/oathwild/data/map.json; the ground is in tiles (see \`baked\`). Do not edit by hand: change the brief, or fix things in the map editor's edits layer (worldbuild/README.md "Hand fixes").`,
    version: 1, seed: W.seed,
    generator: { name: 'worldbuild', brief: b.id, seed: W.seed, fingerprint: W.fingerprint },
    bounds: { ...W.bounds },
    grid: { cell: W.cell, biomeCell: 4, sampleStep: 2 },
    limits: { ...b.limits },
    frame: { _doc: 'The world edge is part of the baked ground; no frame is added on top.', height: 0, width: 1 },
    regions,
    border: pin ? pin.lists.border : { west: W.regionList[0].id, east: W.regionList[0].id, blend: 1, points: [[0, b.size.bounds.minZ], [0, b.size.bounds.maxZ]] },
    hills: pin ? pin.lists.hills : [], ridges: pin ? pin.lists.ridges : [],
    rivers, roads, crossings: W.crossings.map(({ generated, ...c }) => ({ ...c, ...(generated ? { generated } : {}) })).map(({ pinned, ...c }) => c),
    places, areas: strip(W.areas), forests: pin ? strip(pin.lists.forests) : [], fields: strip(W.fields), marshes: pin ? strip(pin.lists.marshes) : [],
    spawn: pin ? pin.map.spawn : { at: W.startAt, shrine: Object.values(W.places).find(p => p.kind === 'shrine')?.id },
    lakes: W.lakes.map(l => ({ id: l.id, name: l.name, level: l.level, at: l.at, area: l.area })),
    sea: { level: W.seaLevel, edges: b.sea.edges },
    setPieces: W.setPieces,
    baked: { _doc: 'Ground tiles (worldbuild/js/export.js "A TILE FILE"). Read with worldbuild/js/export.js readTile().', format: 'WBT1', tile: TILE, cell: W.cell, verts: TILE_VERTS, path: 'tiles/', biomes: BIOMES, regions: W.regionList.map(r => r.id), tiles },
  };
}

/** towns.json for the generated towns (the pinned piece's own rows unchanged first). */
export function toTownsJson(W) {
  const out = {};
  if (W.pin) for (const [k, v] of Object.entries(W.pin.data.towns)) out[k] = v;
  for (const [id, d] of Object.entries(W.townDefs)) out[id] = d;
  return out;
}

export function tileList(W) {
  const B = W.bounds, out = [];
  for (let tx = Math.floor(B.minX / TILE); tx * TILE < B.maxX; tx++) for (let tz = Math.floor(B.minZ / TILE); tz * TILE < B.maxZ; tz++) out.push([tx, tz]);
  return out;
}

/** One tile's layers as bytes (an ArrayBuffer). Vertices outside the world repeat the edge. */
export function writeTile(W, tx, tz) {
  const n = TILE_VERTS, x0 = tx * TILE, z0 = tz * TILE;
  const H = new Float32Array(n * n), Wt = new Float32Array(n * n), K = new Uint8Array(n * n);
  let wet = false;
  for (let k = 0; k < n; k++) for (let i = 0; i < n; i++) {
    const gi = Math.min(W.nx - 1, Math.max(0, Math.round((x0 + i * 2 - W.bounds.minX) / W.cell))), gk = Math.min(W.nz - 1, Math.max(0, Math.round((z0 + k * 2 - W.bounds.minZ) / W.cell)));
    const j = gk * W.nx + gi;
    H[k * n + i] = W.H[j]; Wt[k * n + i] = W.water[j]; K[k * n + i] = W.wkind[j];
    if (!Number.isNaN(W.water[j])) wet = true;
  }
  const bn = TILE / 4, bg = W.T.biomeGrid, Bi = new Uint8Array(bn * bn);
  for (let k = 0; k < bn; k++) for (let i = 0; i < bn; i++) {
    const bi = Math.floor((x0 + i * 4 + 2 - bg.minX) / 4), bk = Math.floor((z0 + k * 4 + 2 - bg.minZ) / 4);
    Bi[k * bn + i] = bi >= 0 && bk >= 0 && bi < bg.nx && bk < bg.nz ? bg.ids[bk * bg.nx + bi] : 8;
  }
  const mn = TILE / 8, M = W.macro, R = new Uint8Array(mn * mn), L = new Uint8Array(mn * mn), F = new Uint8Array(mn * mn);
  for (let k = 0; k < mn; k++) for (let i = 0; i < mn; i++) {
    const mi = Math.min(M.nx - 1, Math.max(0, Math.round((x0 + i * 8 - M.minX) / 8))), mk = Math.min(M.nz - 1, Math.max(0, Math.round((z0 + k * 8 - M.minZ) / 8)));
    const j = mk * M.nx + mi;
    R[k * mn + i] = M.region[j]; L[k * mn + i] = M.level[j]; F[k * mn + i] = Math.round(M.forest[j] * 255);
  }
  const layers = [['height', H], ...(wet ? [['water', Wt]] : []), ['kind', K], ['biome', Bi], ['region', R], ['level', L], ['forest', F]];
  let off = 0;
  const meta = layers.map(([name, a]) => { const m = { name, type: a.constructor.name, n: Math.round(Math.sqrt(a.length)), offset: off, bytes: a.byteLength }; off += a.byteLength; off = (off + 3) & ~3; return m; });
  const header = new TextEncoder().encode(JSON.stringify({ tx, tz, x0, z0, n, layers: meta }));
  const hlen = (header.length + 3) & ~3;
  const buf = new ArrayBuffer(8 + hlen + off), u8 = new Uint8Array(buf);
  u8.set([87, 66, 84, 49]);                         // 'WBT1'
  new DataView(buf).setUint32(4, hlen, true);
  u8.set(header, 8);
  meta.forEach((m, q) => u8.set(new Uint8Array(layers[q][1].buffer), 8 + hlen + m.offset));
  return buf;
}

/** Read a tile file back → { tx, tz, x0, z0, n, height, water|null, kind, biome, region, level, forest }. */
export function readTile(buf) {
  const u8 = new Uint8Array(buf);
  if (String.fromCharCode(...u8.subarray(0, 4)) !== 'WBT1') throw new Error('not a World Build tile');
  const hlen = new DataView(buf).getUint32(4, true);
  const head = JSON.parse(new TextDecoder().decode(u8.subarray(8, 8 + hlen)).replace(/\0+$/, '').trim());
  const out = { ...head, water: null };
  const T = { Float32Array, Uint8Array };
  for (const m of head.layers) out[m.name] = new T[m.type](buf.slice(8 + hlen + m.offset, 8 + hlen + m.offset + m.bytes));
  delete out.layers;
  return out;
}
