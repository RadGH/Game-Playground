def main():
    scowl = {w.strip() for w in open('/usr/share/dict/american-english', encoding='utf-8', errors='ignore') if re.fullmatch(r'[a-z]+', w.strip())}
    cmu = set()
    for line in open(CMU, encoding='utf-8', errors='ignore'):
        w = line.split('\t', 1)[0].split(' ', 1)[0]
        if re.fullmatch(r'[a-z]+', w): cmu.add(w)
    out = []
    for w in top_n_list('en', 80000):
        if not re.fullmatch(r'[a-z]{3,12}', w) or w not in scowl or w not in cmu: continue
        if w in BLOCK or any(s in w for s in STEMS): continue
        out.append(w)
        if len(out) >= TARGET: break
    text = ' '.join(out)
    src = ('// Word Relay dictionary: %d common English words in frequency order (most common first), a-z, 3-12 letters.\n'
           '// Generated by tools/build-words.py (wordfreq rank x SCOWL-50 x CMUdict, minus a blocklist). Do not edit by hand.\n'
           'export const WORDS = %s;\n') % (len(out), '"' + text + '"')
    if len(src.encode()) > MAX_BYTES: sys.exit('too big: %d bytes' % len(src.encode()))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write(src)
    print(len(out), 'words,', len(src.encode()), 'bytes ->', OUT, '| last:', out[-10:])

main()
