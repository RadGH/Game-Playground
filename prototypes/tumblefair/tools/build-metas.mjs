#!/usr/bin/env node
// Writes js/games/metas.js: every minigame's `meta` (title, how-to, controls, arena…) and nothing else, for the
// BROWSER. js/games/index.js imports every game's rules, which the server needs but a phone does not — with 39 games
// that was ~575 KB of rules and word lists downloaded at page load. A game's view.js still loads its own sim.js when
// that game is played. tests/metas.test.js fails if this file is out of date: re-run after changing any meta.
//   node prototypes/tumblefair/tools/build-metas.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { GAMES } from '../js/games/index.js';
export const metasSource = () => `// GENERATED by tools/build-metas.mjs from each js/games/<id>/sim.js — do not edit; re-run the tool.
// The browser's list of minigames (meta only). The server and the tests use js/games/index.js.
export const GAMES = Object.freeze(${JSON.stringify(Object.fromEntries(Object.entries(GAMES).map(([id, g]) => [id, { meta: g.meta }])), null, 1)});
export const gameIds = () => Object.keys(GAMES);
export const metaOf = id => GAMES[id]?.meta || null;
export const loadView = id => import(\`./\${id}/view.js\`);
`;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(fileURLToPath(new URL('../js/games/metas.js', import.meta.url)), metasSource());
  console.log(`metas.js: ${Object.keys(GAMES).length} games`);
}
