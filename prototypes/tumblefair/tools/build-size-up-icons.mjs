#!/usr/bin/env node
// Builds js/games/size-up/icons.js: the Font Awesome Pro 6.7.2 duotone icons Size Up's items name, as plain path
// data (only the icons used, embedded in the game, which the owner's Pro licence allows). Run after changing items.js:
//   node prototypes/tumblefair/tools/build-size-up-icons.mjs [--fa ~/claude/resources/fontawesome-pro-6.7.2-web]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { ITEMS } from '../js/games/size-up/items.js';
const i = process.argv.indexOf('--fa');
const FA = (i > 0 ? process.argv[i + 1] : homedir() + '/claude/resources/fontawesome-pro-6.7.2-web') + '/svgs/duotone/';
const out = {}, missing = [];
for (const name of [...new Set(ITEMS.map(t => t.icon))].sort()) {
  const f = FA + name + '.svg';
  if (!existsSync(f)) { missing.push(name); continue; }
  const s = readFileSync(f, 'utf8');
  const vb = s.match(/viewBox="0 0 (\d+) (\d+)"/), sec = s.match(/class="fa-secondary" d="([^"]*)"/), pri = s.match(/class="fa-primary" d="([^"]*)"/);
  out[name] = [+vb[1], +vb[2], sec ? sec[1] : '', pri ? pri[1] : ''];
}
if (missing.length) { console.error('missing icons:', missing.join(', ')); process.exit(1); }
const src = `// GENERATED by tools/build-size-up-icons.mjs from items.js — do not edit.
// Font Awesome Pro 6.7.2 duotone icons by @fontawesome - https://fontawesome.com License - https://fontawesome.com/license (Commercial License) Copyright 2024 Fonticons, Inc.
// name -> [viewBox width, viewBox height, secondary path, primary path]
export const ICONS = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../js/games/size-up/icons.js', import.meta.url), src);
console.log(Object.keys(out).length, 'icons,', (src.length / 1024).toFixed(1), 'KB');
