#!/usr/bin/env node
// Copies Font Awesome Pro 6.7.2 icons into a game as plain path data (only the icons it uses, embedded, which the
// owner's Pro licence allows). One list per game below; run after changing a list:
//   node prototypes/tumblefair/tools/build-fa-icons.mjs [game-id] [--fa ~/claude/resources/fontawesome-pro-6.7.2-web]
// Writes js/games/<id>/icons.js:  ICONS['style/name'] = [viewBox width, viewBox height, path, secondary path ('' if none)]
// (duotone: path = the primary layer, secondary = the faded layer).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';

const ODD_BASE = ['cat', 'dog', 'fish', 'frog', 'crow', 'dove', 'horse', 'rabbit', 'hippo', 'otter', 'turtle', 'squirrel', 'kiwi-bird', 'duck', 'pig', 'cow', 'sheep', 'spider', 'bee', 'ice-cream', 'apple-whole', 'lemon', 'mushroom', 'umbrella', 'rocket', 'kite', 'hat-wizard', 'tree', 'leaf', 'feather', 'key', 'bell', 'music', 'anchor', 'balloon'];
const ODD_SWAP = ['face-smile', 'face-frown', 'star', 'star-half-stroke', 'heart', 'heart-crack', 'lock', 'lock-open', 'bell-slash', 'volume-high', 'volume-low', 'battery-full', 'battery-half', 'hourglass-start', 'hourglass-end', 'cloud-sun', 'cloud-moon'];
export const LISTS = {
  'odd-one-out': [...ODD_BASE.flatMap(n => ['solid/' + n, 'regular/' + n]), ...ODD_SWAP.map(n => 'solid/' + n)],
  'higher-or-lower': ['ticket', 'candy', 'lollipop', 'popcorn', 'ice-cream', 'balloon', 'hotdog', 'teddy-bear', 'dice', 'gift', 'ferris-wheel', 'crown', 'trophy'].map(n => 'duotone/' + n),
  'potion-mixer': ['mushroom', 'bat', 'spider-web', 'candy-corn', 'bone', 'feather', 'moon', 'sparkles', 'frog', 'acorn', 'worm', 'pumpkin', 'cauldron'].map(n => 'duotone/' + n),
};
const args = process.argv.slice(2), fi = args.indexOf('--fa');
const FA = (fi >= 0 ? args.splice(fi, 2)[1] : homedir() + '/claude/resources/fontawesome-pro-6.7.2-web') + '/svgs/';
const ids = args.length ? args : Object.keys(LISTS);
for (const id of ids) {
  const out = {}, missing = [];
  for (const key of [...new Set(LISTS[id])].sort()) {
    const f = FA + key + '.svg';
    if (!existsSync(f)) { missing.push(key); continue; }
    const s = readFileSync(f, 'utf8'), vb = s.match(/viewBox="0 0 (\d+) (\d+)"/);
    const pri = s.match(/class="fa-primary" d="([^"]*)"/), sec = s.match(/class="fa-secondary" d="([^"]*)"/);
    const one = s.match(/<path d="([^"]*)"/);
    out[key] = [+vb[1], +vb[2], pri ? pri[1] : one[1], sec ? sec[1] : ''];
  }
  if (missing.length) { console.error(id, 'missing icons:', missing.join(', ')); process.exit(1); }
  const src = `// GENERATED by tools/build-fa-icons.mjs (its LISTS['${id}']) — do not edit.
// Font Awesome Pro 6.7.2 icons by @fontawesome - https://fontawesome.com License - https://fontawesome.com/license (Commercial License) Copyright 2024 Fonticons, Inc.
// 'style/name' -> [viewBox width, viewBox height, path, secondary path ('' unless duotone)]
export const ICONS = ${JSON.stringify(out)};
`;
  writeFileSync(new URL(`../js/games/${id}/icons.js`, import.meta.url), src);
  console.log(id, Object.keys(out).length, 'icons,', (src.length / 1024).toFixed(1), 'KB');
}
