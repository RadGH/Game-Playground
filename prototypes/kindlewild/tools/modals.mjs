import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 402, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:8401/prototypes/kindlewild/');
await page.waitForFunction(() => window.gameEye);
await page.locator('#news-slot button').first().tap();
await page.waitForTimeout(400); await page.screenshot({ path: out + '-news.png' });
await page.keyboard.press('Escape'); await page.waitForTimeout(200);
await page.evaluate(() => document.querySelector('.whatsnew-back, .modal-back')?.remove());
await page.tap('#go-journal'); await page.waitForTimeout(300); await page.screenshot({ path: out + '-journal.png' });
await page.locator('.modal .big').tap();
await page.tap('#go-sandbox'); await page.tap('#start-custom'); await page.tap('#base-ok'); await page.waitForTimeout(400);
await page.tap('#btn-menu'); await page.locator('.modal button', { hasText: 'Report' }).tap(); await page.waitForTimeout(300); await page.screenshot({ path: out + '-report.png' });
await page.locator('.modal .small-btn').tap();
await page.tap('#btn-menu'); await page.waitForTimeout(300); await page.screenshot({ path: out + '-menu.png' });
console.log('errors', errors.length ? errors : 'none');
await browser.close();
