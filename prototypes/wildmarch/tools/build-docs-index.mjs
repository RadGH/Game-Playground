#!/usr/bin/env node
/**
 * build-docs-index.mjs — writes docs/index.json, the page list the design-bible site reads.
 *
 * Run after adding, removing or renaming a doc:
 *   node prototypes/wildmarch/tools/build-docs-index.mjs
 *
 * Every .md under docs/ is listed, grouped by GROUPS below (first match wins), in file-name order.
 * A page's title is its first "# " heading; `short` is the part after the last colon so the sidebar
 * stays narrow. Class files take their display name from data/canon.json.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const docsDir = join(root, 'docs');
const canon = JSON.parse(readFileSync(join(root, 'data/canon.json'), 'utf8'));
const classNames = Object.fromEntries(canon.classes.map(([id, name]) => [id, name]));
const classOrder = canon.classes.map(([id]) => id);

const GROUPS = [
  ['Start here', id => ['00-OVERVIEW', 'WOW-AUDIT', 'QUESTIONS', 'CHANGELOG'].includes(id)],
  ['World & story', id => /^(01|14)-/.test(id)],
  ['Playing the game', id => /^(02|03|04)-/.test(id)],
  ['Systems', id => /^(05|06|07|08|09|19|20)-/.test(id)],
  ['Classes', id => id.startsWith('classes/')],
  ['Enemies & bosses', id => /^(10|11|12|13)-/.test(id)],
  ['Online, tech & build plan', id => /^(15|16|17|18)-/.test(id)],
  ['Notes for the builder', () => true],
];

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : name.endsWith('.md') ? [p] : [];
  });
}

const docs = walk(docsDir).map(path => {
  const id = relative(docsDir, path).replace(/\\/g, '/').replace(/\.md$/, '');
  const text = readFileSync(path, 'utf8');
  const h1 = (text.match(/^#\s+(.+)$/m) || [, id])[1].replace(/[`*_]/g, '').trim();
  let short = h1.includes(':') ? h1.slice(h1.lastIndexOf(':') + 1).trim() : h1.replace(/^WILDMARCH\s*[—-]\s*/i, '');
  if (id.startsWith('classes/')) short = classNames[id.slice(8)] || short;
  const num = id.match(/^(\d\d)-/);
  if (num && !short.startsWith(num[1])) short = `${num[1]} · ${short}`;
  return { id, title: h1, short: short.slice(0, 48), lines: text.split('\n').length, words: (text.match(/\S+/g) || []).length };
});

const order = d => d.id.startsWith('classes/') ? classOrder.indexOf(d.id.slice(8)) : 0;
const groups = GROUPS.map(([title]) => ({ title, docs: [] }));
for (const d of docs) {
  const g = GROUPS.findIndex(([, test]) => test(d.id));
  groups[g].docs.push(d);
}
for (const g of groups) g.docs.sort((a, b) => order(a) - order(b) || a.id.localeCompare(b.id));
const start = groups[0].docs;
start.sort((a, b) => ['00-OVERVIEW', 'WOW-AUDIT', 'QUESTIONS', 'CHANGELOG'].indexOf(a.id) - ['00-OVERVIEW', 'WOW-AUDIT', 'QUESTIONS', 'CHANGELOG'].indexOf(b.id));

const out = { _doc: 'Generated by tools/build-docs-index.mjs — do not edit by hand.', generated: new Date().toISOString(), groups: groups.filter(g => g.docs.length) };
writeFileSync(join(docsDir, 'index.json'), JSON.stringify(out, null, 1) + '\n');
const total = docs.reduce((s, d) => s + d.words, 0);
console.log(`docs/index.json: ${docs.length} pages, ${total.toLocaleString()} words`);
