// M4 screenshots: a grown town, the Economy and People screens, a data view.
import { chromium } from 'playwright';
const [out, w = 402, h = 780] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
const logs = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') logs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
await page.goto('http://localhost:8401/prototypes/stoneward/?shots&dev', { waitUntil: 'networkidle' });
await page.click('#btn-new'); await page.click('#nw-go');
await page.waitForFunction(() => window.gameEye.state().screen === 'landing', null, { timeout: 30000 });
await page.mouse.click(+w / 2, +h / 2); await page.waitForTimeout(1500);
await page.click('#land-go');
await page.waitForFunction(() => window.gameEye.state().screen === 'hud', null, { timeout: 10000 });
await page.evaluate(() => window.gameEye.speed(8));
await page.waitForTimeout(60000);
await page.evaluate(() => window.gameEye.speed(1));
const st = await page.evaluate(() => window.gameEye.state());
await page.evaluate(({ x, y }) => window.gameEye.fly(x, y, 3), st.town.towns[0]);
await page.waitForTimeout(2500);
await page.screenshot({ path: out + '-town.png' });
await page.click('[data-tab="info"]'); await page.waitForTimeout(300);
await page.click('#dock-panel button:text-is("Economy")'); await page.waitForTimeout(500);
await page.screenshot({ path: out + '-economy.png' });
await page.click('#dock-panel button:text-is("People")'); await page.waitForTimeout(500);
await page.screenshot({ path: out + '-people.png' });
await page.click('[data-tab="layers2"]'); await page.waitForTimeout(300);
await page.click('#dock-panel button:text-is("Water")'); await page.waitForTimeout(1500);
await page.screenshot({ path: out + '-water.png' });
console.log(JSON.stringify(st.town?.pop), JSON.stringify(st.town?.kinds));
console.log(logs.join('\n'));
await browser.close();
